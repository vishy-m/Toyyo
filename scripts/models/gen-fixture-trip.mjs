// One-off: builds components/map/fixtures.ts from a real Mapbox Directions route
// (downtown Austin -> I-35 north -> The Domain). Reads the token from .env; never prints it.
// Usage: node scripts/models/gen-fixture-trip.mjs
import fs from "node:fs";
import * as turf from "@turf/turf";

const env = fs.readFileSync(".env", "utf8");
const token = env.match(/^MAPBOX=(.*)$/m)[1].trim().replace(/^"|"$/g, "");
const coords = [
  [-97.7445, 30.2649], // Congress Ave & 3rd St (downtown)
  [-97.7375, 30.2672], // E 6th / downtown grid
  [-97.7215, 30.2905], // I-35 near MLK
  [-97.7127, 30.3330], // I-35 north
  [-97.7225, 30.4005], // The Domain
];
const url = `https://api.mapbox.com/directions/v5/mapbox/driving/${coords.map((c) => c.join(",")).join(";")}?geometries=geojson&overview=full&annotations=duration,distance,speed&access_token=${token}`;
const res = await fetch(url);
if (!res.ok) throw new Error("directions failed " + res.status);
const json = await res.json();
const route = json.routes[0];
const line = route.geometry.coordinates;
const durs = route.legs.flatMap((l) => l.annotation.duration);
// cumulative time per vertex
const times = [0];
for (const d of durs) times.push(times[times.length - 1] + d);
// Resample to ~320 points evenly in time.
const total = times[times.length - 1];
const N = 320;
const path = [];
let j = 0;
for (let k = 0; k < N; k++) {
  const t = (k / (N - 1)) * total;
  while (j < times.length - 2 && times[j + 1] < t) j++;
  const f = times[j + 1] === times[j] ? 0 : (t - times[j]) / (times[j + 1] - times[j]);
  const a = line[j], b = line[j + 1];
  path.push([+(a[0] + (b[0] - a[0]) * f).toFixed(6), +(a[1] + (b[1] - a[1]) * f).toFixed(6), Math.round(t * 10) / 10]);
}
const miles = turf.length(turf.lineString(path.map((p) => [p[0], p[1]])), { units: "miles" });
const at = (frac) => path[Math.round(frac * (N - 1))];
const ev = (frac, type, scoreDelta) => { const p = at(frac); return { t: p[2], type, scoreDelta, lngLat: [p[0], p[1]] }; };
const events = [
  ev(0.12, "harsh-corner", -1),
  ev(0.27, "fast-accel", -1),
  ev(0.46, "speeding-start", 0),
  ev(0.58, "speeding-end", -3),
  ev(0.71, "hard-brake", -2),
  ev(0.9, "hard-brake", -2),
];
const durationS = path[N - 1][2];
const start = new Date("2026-10-14T18:52:00-05:00");
const end = new Date(start.getTime() + durationS * 1000);
const trip = {
  id: "fixture-maya-commute",
  personaId: "maya",
  start: start.toISOString(),
  end: end.toISOString(),
  miles: +miles.toFixed(1),
  highwayPct: 0.68,
  nightPct: 0.4,
  speedingPct: 0.12,
  hardBrakes: 2,
  fastAccels: 1,
  harshCorners: 1,
  category: "commute",
  destinationLabel: "The Domain, North Austin",
  score: 84,
  showcase: true,
  path,
  events,
};
const out = `// Generated by scripts/models/gen-fixture-trip.mjs from a real Mapbox Directions route.
// Sandbox fixture for /lab until task 01's real trips land. Do not edit by hand.
import type { Trip } from "@/lib/types";

export const FIXTURE_TRIP: Trip = ${JSON.stringify(trip)};
`;
fs.writeFileSync("components/map/fixtures.ts", out);
console.log("points", N, "miles", miles.toFixed(2), "duration s", durationS);
